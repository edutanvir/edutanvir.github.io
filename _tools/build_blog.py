#!/usr/bin/env python3
"""
Builds the blog from plain Markdown files.

    1. Write a post in  _posts-src/my-post.md
    2. Run               python3 _tools/build_blog.py
    3. Commit and push   (the generated files live in blog/)

Why generate static pages instead of loading Markdown in the browser?
LinkedIn, Slack and WhatsApp build their link preview (the big image + title)
by reading the page's HTML WITHOUT running any JavaScript. Pre-built pages
carry the right preview tags, so a pasted link looks great everywhere.

One-time setup:   pip3 install markdown
Optional:         pip3 install pillow   (adds image sizes, which stops page jumping)

Front matter (the block at the top of each post):

    ---
    title: A short, specific title
    date: 2026-11-07
    description: One or two sentences. Shown on the card and in link previews.
    image: my-cover.jpg          # file inside blog/images/  (1200 x 627 is ideal)
    image_alt: What the picture shows
    tags: Azure, Databricks
    draft: true                  # optional: true = not built yet
    ---

Using an infographic (any shape) as the post's main picture:

    image: my-infographic.webp   # shown in full, never cropped, click to open full size
    image_layout: natural
    preview: my-infographic-preview.jpg   # 1200 x 627 picture for the blog list and LinkedIn

The home page (index.html) shows your 3 newest posts between the BLOG-LATEST markers.
The build refreshes that block for you; everything outside the markers is yours to edit.

Files whose names start with an underscore (for example _formatting-guide.md)
are ignored by the build, so you can keep notes and templates there.
"""

