def floaters(*items):
    positions = [("78%", "16%", "1.2", "#8f7bff", "64px", "7s"),
                 ("90%", "42%", "0.8", "#ff7ab8", "50px", "8s"),
                 ("70%", "58%", "1.4", "#2997ff", "54px", "6s")]
    out = []
    for icon, (x, y, d, c, s, t) in zip(items, positions):
        out.append(
            f'<span class="fi" style="--x:{x};--y:{y};--d:{d};--c:{c}"><span class="fi-tile" '
            f'style="--s:{s};--t:{t}"><svg class="ico"><use href="#{icon}"/></svg></span></span>')
    return '<div class="float-icons" aria-hidden="true">' + "".join(out) + "</div>"


def tag_list(tags):
    if not tags:
        return ""
    return '<ul class="tag-list" role="list">' + "".join(f"<li>{esc(t)}</li>" for t in tags) + "</ul>"


