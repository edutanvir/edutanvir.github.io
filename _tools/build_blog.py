def fail(message):
    sys.exit(f"\nProblem: {message}\n")


# ---------------------------------------------------------------- reading ----
def parse_post(path):
    raw = path.read_text(encoding="utf-8").lstrip("﻿")
    match = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", raw, re.S)
    if not match:
        fail(f"{path.name} must start with a front-matter block between two '---' lines.")

    meta = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = re.sub(r"\s+#.*$", "", value.strip())      # allow trailing comments
        meta[key.strip().lower()] = value.strip().strip("\"'")

    for key in ("title", "date", "description"):
        if not meta.get(key):
            fail(f"{path.name} is missing '{key}:' in its front matter.")

    try:
        date = dt.date.fromisoformat(meta["date"])
    except ValueError:
        fail(f"{path.name}: date must look like 2026-11-07 (got '{meta['date']}').")

    tags = [t.strip() for t in meta.get("tags", "").strip("[]").split(",") if t.strip()]
    body = match.group(2).strip()

    return {
        "slug": path.stem,
        "title": meta["title"],
        "date": date,
        "description": meta["description"],
        "image": meta.get("image") or DEFAULT_COVER,
        "image_alt": meta.get("image_alt") or meta["title"],
        "layout": "natural" if meta.get("image_layout", "").lower() == "natural" else "cover",
        "preview": meta.get("preview") or "",
        "tags": tags,
        "draft": meta.get("draft", "").lower() in ("true", "yes", "1"),
        "body_md": body,
        "words": len(re.findall(r"\w+", body)),
    }


def nice_date(d):
    return f"{d:%B} {d.day}, {d.year}"


def minutes(post):
    return max(1, round(post["words"] / WORDS_PER_MINUTE))


def image_size(name):
    if Image is None:
        return 1200, 627
    try:
        with Image.open(IMAGES / name) as im:
            return im.size
    except Exception:
        return 1200, 627


# -------------------------------------------------------------- markdown ----
def render_body(post):
    text = markdown.markdown(
        post["body_md"], extensions=["fenced_code", "tables", "sane_lists"], output_format="html5"
    )
    text = re.sub(r"<(/?)h1\b", r"<\1h2", text)
    # Wide tables scroll sideways inside their own box instead of stretching the page on phones
    text = text.replace("<table>", '<div class="table-wrap"><table>').replace("</table>", "</table></div>")             # the page already has one h1

    def fix_src(src):
        if re.match(r"^(https?:)?//", src) or src.startswith("/") or src.startswith("images/"):
            return src
        return f"images/{src}"

    def figure(m):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1)))
        src = fix_src(attrs.get("src", ""))
        alt = attrs.get("alt", "")
        caption = attrs.get("title", "")
        size = ""
        if src.startswith("images/"):
            if not (OUT / src).exists():
                print(f"  warning: {post['slug']}.md uses {src} but that file does not exist in blog/images/")
            else:
                w, h = image_size(src[len("images/"):])
                size = f' width="{w}" height="{h}"'
        cap = f"<figcaption>{caption}</figcaption>" if caption else ""
        return f'<figure class="post-figure"><img src="{src}" alt="{alt}"{size} loading="lazy">{cap}</figure>'

    text = re.sub(r"<p>\s*<img ([^>]*?)\s*/?>\s*</p>", figure, text)
    text = re.sub(r'(<img [^>]*?src=")(?!https?:|//|/|images/)([^"]+)"', r'\1images/\2"', text)
    return text


